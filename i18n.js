/* ══ Engine de tradução ══ */
function t(key) {
  const lang = localStorage.getItem('lang') || 'pt';
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS['pt'][key] || key;
}

function applyTranslations() {
  const lang = localStorage.getItem('lang') || 'pt';
  const dict = TRANSLATIONS[lang];
  if (!dict) return;

  /* Textos simples */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  /* Placeholders */
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });

  /* Label do botão — mostra o idioma para ONDE vai trocar */
  const lbl = document.getElementById('langLabel');
  if (lbl) lbl.textContent = lang === 'pt' ? 'ES' : 'PT';

  /* html lang */
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'es';
}

function toggleLang() {
  const current = localStorage.getItem('lang') || 'pt';
  const next = current === 'pt' ? 'es' : 'pt';
  localStorage.setItem('lang', next);
  applyTranslations();
}

/* Inicializa ao carregar — funciona no head ou no final do body */
function initI18n() {
  applyTranslations();

  // Busca o botão e conecta o evento
  const btn = document.getElementById('langToggle');
  if (btn) {
    // Remove listener antigo substituindo o nó
    const fresh = btn.cloneNode(true);
    btn.parentNode.replaceChild(fresh, btn);
    fresh.addEventListener('click', function() {
      toggleLang();
    });
  }
}

// Funciona independente de onde o script está
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}

